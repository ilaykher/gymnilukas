ALTER TABLE members
  ADD COLUMN IF NOT EXISTS mem_username varchar(80),
  ADD COLUMN IF NOT EXISTS mem_pin_hash varchar(100);

CREATE UNIQUE INDEX IF NOT EXISTS members_mem_username_lower_unique
  ON members (lower(mem_username))
  WHERE mem_username IS NOT NULL;

ALTER TABLE emp_acc
  ADD COLUMN IF NOT EXISTS emp_job_title varchar(50);

ALTER TABLE login_auth
  ADD COLUMN IF NOT EXISTS auth_must_change_password boolean NOT NULL DEFAULT false;

ALTER TABLE membership
  ADD COLUMN IF NOT EXISTS membership_type varchar(20);

ALTER TABLE transactions
  ADD COLUMN IF NOT EXISTS payment_method varchar(20),
  ADD COLUMN IF NOT EXISTS payment_reference varchar(32);

ALTER TABLE walk_in_attendance
  ADD COLUMN IF NOT EXISTS wiatd_contact_num varchar(11);

CREATE TABLE IF NOT EXISTS activity_logs (
  activity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_emp_id integer REFERENCES emp_acc(emp_id),
  activity_action varchar(80) NOT NULL,
  entity_type varchar(40) NOT NULL,
  entity_id bigint,
  activity_details jsonb NOT NULL DEFAULT '{}'::jsonb,
  activity_date_created timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS activity_logs_date_created_idx
  ON activity_logs (activity_date_created DESC);

CREATE INDEX IF NOT EXISTS transactions_date_created_idx
  ON transactions (transaction_date_created DESC);

CREATE INDEX IF NOT EXISTS member_attendance_time_in_idx
  ON member_attendance (atd_time_in DESC);

CREATE INDEX IF NOT EXISTS walk_in_attendance_time_in_idx
  ON walk_in_attendance (wiatd_time_in DESC);
